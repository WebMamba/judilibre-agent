<?php

declare(strict_types=1);

namespace App\Tests\Dossier;

use App\Entity\Dossier;
use App\Judilibre\Citation;
use App\Repository\DossierRepository;
use App\Research\Consultation;
use App\Research\Phase;
use App\Research\ResearchState;
use App\Research\RetainedDecision;
use App\Security\EnvUserProvider;
use App\Tests\Support\FakeJudilibre;
use App\Tests\Support\ScriptedPlatform;
use Symfony\AI\Platform\Result\Stream\Delta\TextDelta;
use Symfony\Bundle\FrameworkBundle\KernelBrowser;
use Symfony\Bundle\FrameworkBundle\Test\WebTestCase;
use Symfony\Component\Serializer\Normalizer\NormalizerInterface;
use Symfony\Contracts\Translation\TranslatorInterface;

/**
 * With APP_LOCALE=en, the whole application speaks English: the pages, the labels the
 * page hands its controllers, the Word export, the citations, and the agent is told
 * to write in English.
 */
final class EnglishInterfaceTest extends WebTestCase
{
    private const string DECISION = '65f1c0a2b4e3d2001a7c9e11';

    private KernelBrowser $client;

    protected function setUp(): void
    {
        $_SERVER['APP_LOCALE'] = $_ENV['APP_LOCALE'] = 'en';
        ScriptedPlatform::reset();
        $this->client = self::createClient();
        $this->client->loginUser(self::getContainer()->get(EnvUserProvider::class)->loadUserByIdentifier('juriste@example.com'));
    }

    protected function tearDown(): void
    {
        parent::tearDown();
        $_SERVER['APP_LOCALE'] = $_ENV['APP_LOCALE'] = 'fr';
    }

    public function testTheDossiersAreListedInEnglish(): void
    {
        $this->client->request('GET', '/');

        self::assertResponseIsSuccessful();
        self::assertSelectorTextContains('h1', 'My cases');
        self::assertSelectorTextContains('main', 'New case');
    }

    public function testADeliveredDossierReadsInEnglish(): void
    {
        $this->save($this->delivered($id = 'en_'.bin2hex(random_bytes(4))));

        $crawler = $this->client->request('GET', '/dossiers/'.$id);

        self::assertResponseIsSuccessful();
        self::assertSelectorTextContains('nav', 'Delivered');
        self::assertSelectorTextContains('#consultation-panel', 'Export to Word');
        self::assertSelectorTextContains('#consultation-panel', 'Short answer');
        self::assertSelectorTextContains('#consultation-panel', 'Annex — Decisions cited');
        self::assertSelectorTextContains('#consultation-panel', 'It does not replace a lawyer\'s analysis');
        self::assertSelectorTextContains('#filters-panel', 'Court of Cassation');
        self::assertSelectorTextContains('[data-agent-chat-target="messages"]', 'Writing the section “Discussion”');

        $root = $crawler->filter('[data-controller~="agent-chat"]');
        $chat = json_decode((string) $root->attr('data-agent-chat-labels-value'), true);
        self::assertSame('{count} decisions kept out of {candidates}', $chat['retained_many']);
        self::assertSame('Risk assessment', $chat['sections']['risques']);
        self::assertSame('Pin', json_decode((string) $root->attr('data-research-labels-value'), true)['pin']);
    }

    public function testTheWordExportIsInEnglish(): void
    {
        $this->save($this->delivered($id = 'en_'.bin2hex(random_bytes(4))));

        $this->client->request('GET', '/dossiers/'.$id.'/consultation.docx');

        self::assertResponseIsSuccessful();
        $file = tempnam(sys_get_temp_dir(), 'docx');
        file_put_contents($file, $this->client->getInternalResponse()->getContent());
        $zip = new \ZipArchive();
        self::assertTrue($zip->open($file));
        $xml = (string) $zip->getFromName('word/document.xml');
        $footer = implode('', array_map(static fn (int $i): string => (string) $zip->getFromIndex($i), array_filter(range(0, $zip->numFiles - 1), static fn (int $i): bool => str_starts_with((string) $zip->getNameIndex($i), 'word/footer'))));
        unlink($file);
        self::assertStringContainsString('Legal opinion', $xml);
        self::assertStringContainsString('Recommended arguments for the hearing', $xml);
        self::assertStringContainsString('Annex — Decisions cited', $xml);
        self::assertStringContainsString('Decision-support document generated by artificial intelligence', $footer);
    }

    public function testACitationIsWrittenInEnglish(): void
    {
        $decision = new FakeJudilibre()->catalog()->find(self::DECISION);

        self::assertSame('Court of Cassation, Social Chamber, 13 March 2024, No. 22-18.457', Citation::of($decision, self::getContainer()->get(TranslatorInterface::class)));
    }

    public function testTheAgentIsToldToWriteInEnglish(): void
    {
        ScriptedPlatform::$rounds = [[new TextDelta('Hello.')]];

        $this->client->request('POST', '/agent/stream', server: ['CONTENT_TYPE' => 'application/json'], content: json_encode([
            'threadId' => 'en_'.bin2hex(random_bytes(6)), 'runId' => 'r1',
            'messages' => [['id' => 'u1', 'role' => 'user', 'content' => 'My client was dismissed.']],
        ], \JSON_THROW_ON_ERROR));
        $this->client->getInternalResponse();

        $sent = json_encode(ScriptedPlatform::$calls[0]['input'], \JSON_THROW_ON_ERROR | \JSON_UNESCAPED_UNICODE);
        self::assertStringContainsString("Langue de l'utilisateur (code ISO 639-1) : en.", $sent);
    }

    private function delivered(string $id): Dossier
    {
        $state = new ResearchState();
        $state->phase = Phase::Livre;
        $state->title = 'Dismissal during sick leave';
        $state->retained = [new RetainedDecision(self::DECISION, 'a1', 'Court of Cassation, Social Chamber, 13 March 2024, No. 22-18.457')];
        $state->consultation = new Consultation();
        foreach (array_keys(Consultation::SECTIONS) as $section) {
            $state->consultation->write($section, 'The section '.$section.' [['.self::DECISION.']].');
        }

        $dossier = new Dossier($id, 'juriste@example.com');
        $dossier->recordState((array) self::getContainer()->get(NormalizerInterface::class)->normalize($state));
        $dossier->recordMessages([
            ['id' => 'u1', 'role' => 'user', 'content' => 'My client was dismissed during a sick leave.'],
            ['id' => 'm1', 'role' => 'assistant', 'content' => '', 'toolCalls' => [
                ['id' => 'c1', 'type' => 'function', 'function' => ['name' => 'write_section', 'arguments' => '{"section":"discussion"}']],
            ]],
        ]);

        return $dossier;
    }

    private function save(Dossier $dossier): void
    {
        self::getContainer()->get(DossierRepository::class)->save($dossier);
    }
}
